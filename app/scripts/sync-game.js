#!/usr/bin/env node
/* Embeds the game in the app.

   npm run sync-game            runs ../tools/build-single.py and writes src/game-html.js
   node scripts/sync-game.js --check
                                rebuilds to a temp file and fails if src/game-html.js is not byte-identical to it
   ... --check --lenient        the same, but only warns when the game sources or python3 are not there
                                (used as the EAS pre-install hook, where a stale embed must stop the build
                                but a missing Python must not)

   The game is embedded as a JavaScript module that exports the HTML as a string. See README, "Why a JS module". */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const APP = path.join(__dirname, '..');
const BUILDER = path.join(APP, '..', 'tools', 'build-single.py');
const OUT = path.join(APP, 'src', 'game-html.js');
const args = new Set(process.argv.slice(2));
const check = args.has('--check');
const lenient = args.has('--lenient');

const sha256 = buf => crypto.createHash('sha256').update(buf).digest('hex');

function soft(msg) {
  if (lenient) { console.warn('sync-game: ' + msg + ' Using the committed src/game-html.js as it is.'); process.exit(0); }
  console.error('sync-game: ' + msg); process.exit(1);
}

function build() {
  if (!fs.existsSync(BUILDER)) soft('cannot find ' + path.relative(APP, BUILDER) + '.');
  const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'omt-')), 'game.html');
  const r = spawnSync('python3', [BUILDER, tmp], { encoding: 'utf8' });
  if (r.error) soft('python3 is not available (' + r.error.code + ').');
  if (r.status !== 0) { console.error(r.stdout + r.stderr); console.error('sync-game: build-single.py failed.'); process.exit(1); }
  const bytes = fs.readFileSync(tmp);
  fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
  return bytes;
}

/* The shell relies on these being present in the page. If the game drops one, fail here rather than on a phone. */
const CONTRACT = [
  ['<head>', 'the shell inserts its bootstrap script straight after <head>'],
  ['window.__OMT_NATIVE__', 'the game reads its save from window.__OMT_NATIVE__'],
  ['ReactNativeWebView', 'the game posts save and haptic messages'],
  ['--st:', 'the shell overrides the --st/--sb/--sl/--sr inset variables'],
  ['--sb:', 'the shell overrides the --st/--sb/--sl/--sr inset variables'],
  ['back()', 'the hardware back button calls window.__omt.back()'],
  ['visibilitychange', 'the game freezes when the app is backgrounded'],
];

function moduleSource(bytes) {
  const html = bytes.toString('utf8');
  if (!Buffer.from(html, 'utf8').equals(bytes)) { console.error('sync-game: the build output is not valid UTF-8.'); process.exit(1); }
  const missing = CONTRACT.filter(([needle]) => !html.includes(needle));
  if (missing.length) {
    missing.forEach(([needle, why]) => console.error('sync-game: the built page no longer contains "' + needle + '" (' + why + ').'));
    process.exit(1);
  }
  // JSON.stringify gives a valid JavaScript string literal; U+2028/9 are escaped so that every tool agrees on line ends.
  const literal = JSON.stringify(html).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return '/* GENERATED by `npm run sync-game` from ../tools/build-single.py. Do not edit; do commit. */\n' +
    'module.exports = {\n' +
    '  GAME_HTML_SHA256: ' + JSON.stringify(sha256(bytes)) + ',\n' +
    '  GAME_HTML_BYTES: ' + bytes.length + ',\n' +
    '  GAME_HTML: ' + literal + ',\n' +
    '};\n';
}

const bytes = build();
const source = moduleSource(bytes);

if (!check) {
  fs.writeFileSync(OUT, source);
  console.log('sync-game: wrote src/game-html.js (' + bytes.length + ' bytes of HTML, sha256 ' + sha256(bytes).slice(0, 12) + ')');
  process.exit(0);
}

if (!fs.existsSync(OUT)) { console.error('sync-game: src/game-html.js is missing. Run `npm run sync-game`.'); process.exit(1); }
const embedded = Buffer.from(require(OUT).GAME_HTML, 'utf8');
if (!embedded.equals(bytes)) {
  console.error('sync-game: src/game-html.js is STALE: embedded ' + embedded.length + ' bytes (sha256 ' + sha256(embedded).slice(0, 12) +
    '), fresh build ' + bytes.length + ' bytes (sha256 ' + sha256(bytes).slice(0, 12) + '). Run `npm run sync-game` and commit the result.');
  process.exit(1);
}
console.log('sync-game: OK, embedded HTML is byte-identical to the build output (' + bytes.length + ' bytes, sha256 ' + sha256(bytes) + ')');
