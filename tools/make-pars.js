// Writes one-man-team/js/levels/pars.js: the bot's move time for every level, which the star thresholds are built on.
// Run after any change to a level, a bot script or the engine: node tools/make-pars.js
const fs = require('fs'), path = require('path');
const { FB, SCRIPTS } = require('./load.js');
const { makeBot } = require('./bots.js');
const pars = FB.LEVELS.map((L, li) => {
  const recs = L.att.map(() => null);
  for (let r = 0; r < L.order.length; r++) {
    const live = L.order[r], S = FB.makeSim(L, recs, live), bot = makeBot(SCRIPTS[li][r]);
    while (S.status === 'play') FB.step(S, bot(S));
    if (S.status === 'fail') throw new Error('level ' + (li + 1) + ' not beaten');
    recs[live] = FB.finalRec(S);
  }
  const R = FB.makeSim(L, recs, -1); while (R.status === 'play') FB.step(R, {});
  return +(R.tick / 60).toFixed(1);
});
const out = `/* Generated by tools/make-pars.js. Do not edit. The bot's move time per level, in level order. */
(function (root) {
  const P = [${pars.join(', ')}];
  const L = root.OMT_LEVELS || [];
  for (let i = 0; i < L.length && i < P.length; i++) L[i].bot = P[i];
})(typeof module !== 'undefined' ? global : window);
`;
fs.writeFileSync(path.join(__dirname, '..', 'one-man-team', 'js', 'levels', 'pars.js'), out);
console.log('pars:', pars.join(', '));
