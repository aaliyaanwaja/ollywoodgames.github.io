#!/usr/bin/env python3
"""Packs one-man-team/audio/*.mp3 into one-man-team/js/sounds.js as base64 data, so the game can play recorded sounds
from a single HTML file, from file:// and inside the app (no fetch, no network). Rerun after changing any sound.
Usage: python3 tools/make-sounds.py"""
import base64, os, glob, json
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'one-man-team')
out = {}
for f in sorted(glob.glob(os.path.join(root, 'audio', '*.mp3'))):
    out[os.path.basename(f)[:-4]] = 'data:audio/mpeg;base64,' + base64.b64encode(open(f, 'rb').read()).decode()
js = ('/* Generated by tools/make-sounds.py from one-man-team/audio/ (sources and licences in audio/CREDITS.md). Do not edit. */\n'
      'window.OMT_SOUNDS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
open(os.path.join(root, 'js', 'sounds.js'), 'w').write(js)
print('wrote js/sounds.js', len(js), 'bytes,', len(out), 'sounds')
