#!/usr/bin/env python3
"""Writes the web-side identity assets (Ghost trail icon, D4 Two-tone wordmark) from tools/brand.py.

    python3 tools/make-brand.py                       wordmarks, lockups (no browser needed)
    python3 tools/make-brand.py --share RAW.png       also the 1200 x 630 share card, with RAW.png (an untouched game
                                                      capture, e.g. from app/scripts/make-screenshots.py --keep-raw) as
                                                      the printed plate

Writes:
  one-man-team/js/brand.js            the in-game wordmarks as inline SVG strings (masthead and cover)
  one-man-team/icons/lockup.svg       icon + one-line wordmark, light (transparent) and dark (press, posts)
  one-man-team/icons/lockup-dark.svg
  one-man-team/icons/lockup-stack.svg icon + stacked wordmark (the landing page), light and dark
  one-man-team/icons/lockup-stack-dark.svg
  one-man-team/icons/wordmark.svg     single-line wordmark, ink and paper
  one-man-team/icons/wordmark-dark.svg
  one-man-team/icons/share-1200x630.png   Open Graph / Twitter card (with --share)

The app icons, favicons and store art are drawn by app/scripts/make-art.py from the same module."""
import argparse, asyncio, base64, io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brand as B

GAME = os.path.join(B.ROOT, 'one-man-team')
ICONS = os.path.join(GAME, 'icons')


def em(v):
    return ('%.3f' % (v / 1000)).rstrip('0').rstrip('.')


def game_wordmarks():
    """Two sizes, each matched to the box of the live text it replaces in css/style.css:
       .title      40px Anton, line-height .95, 2px tomato shadow   -> one line, 0.95em high
       .title.big  clamp(64px, 24.5vw, 124px), line-height .9, 4px shadow, always two lines -> 1.8em high
    The lettering sits where the live text sat; only the ball widens the box."""
    line, lw, lhh = B.wordmark(lh=0.95, uid='wl',
                               attrs=' class="wm" role="img" aria-label="%s" focusable="false" style="width:%sem"' % (B.NAME, em(B.wordmark_box(lh=.95)[0])))
    stack, sw, shh = B.wordmark(lines=B.LINES, lh=0.9, uid='ws',
                                attrs=' class="wm" role="img" aria-label="%s" focusable="false" style="width:%sem"' % (B.NAME, em(B.wordmark_box(B.LINES, lh=.9)[0])))
    js = ('/* Generated by tools/make-brand.py from tools/brand.py. Do not edit by hand.\n'
          '   The D4 Two-tone wordmark (docs/brand/2026-11-27-wordmark-drafts.md): Anton outlines, so no font is needed\n'
          '   and it stays sharp at any size. game.js uses it only while GAME_NAME matches `name`. */\n'
          'window.OMT_BRAND = {\n  name: %r,\n  line: %r,\n  stack: %r\n};\n') % (B.NAME, line, stack)
    path = os.path.join(GAME, 'js', 'brand.js')
    open(path, 'w').write(js)
    print('  one-man-team/js/brand.js  %d bytes' % len(js))


def static_svgs():
    for dark in (False, True):
        sfx = '-dark' if dark else ''
        for kind, stacked in (('lockup', False), ('lockup-stack', True)):
            lk, W, H = B.lockup(dark, stacked=stacked)
            pad = 40 if dark else 0            # the dark ones carry their own ink ground
            body = lk[lk.index('>') + 1:-len('</svg>')]
            out = B.svg(W + pad * 2, H + pad * 2, '<g transform="translate(%d %d)">%s</g>' % (pad, pad, body), bg=B.INK if dark else None)
            open(os.path.join(ICONS, '%s%s.svg' % (kind, sfx)), 'w').write(out + '\n')
        wm, _, _ = B.wordmark(main=B.PAPER if dark else B.INK, uid='wm', lh=1.0, size=230)
        open(os.path.join(ICONS, 'wordmark%s.svg' % sfx), 'w').write(wm + '\n')
    print('  one-man-team/icons/lockup[-stack][-dark].svg, wordmark[-dark].svg')


